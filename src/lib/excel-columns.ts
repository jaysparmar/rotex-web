/** 0-based column index -> spreadsheet-style letters ("A", "B", ..., "Z", "AA", ...). */
export function excelColumnLabel(index: number): string {
  let n = index + 1;
  let label = "";
  while (n > 0) {
    const rem = (n - 1) % 26;
    label = String.fromCharCode(65 + rem) + label;
    n = Math.floor((n - 1) / 26);
  }
  return label;
}
